#!/usr/bin/env node
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
const root = process.cwd();
const read = (p) => readFileSync(join(root, p), "utf8");
assert(existsSync("lib/products/authorization.ts"));
assert(existsSync("lib/actions/seller-products.ts"));
assert(existsSync("lib/products/digital-taxonomy.ts"));
assert(existsSync("components/product/CategoryTreeSelect.tsx"));
assert(existsSync("components/product/ProductTypeSelector.tsx"));
assert(existsSync("app/api/identity/verification/business/route.ts"));
const auth = read("lib/products/authorization.ts");
assert(auth.includes("business_verification_required"));
assert(auth.includes("pending_review"));
assert(auth.includes("businessVerificationCustomerStatus"));
assert(auth.includes('s === "verified" || s === "approved"'));
const api = read("app/api/products/route.ts");
assert(api.includes("assertCanCreateProductType"));
assert(api.includes("initialStatusForVendorSubmit"));
const form = read("components/product/ProductFormShell.tsx");
assert(form.includes('product_type: "digital"'));
assert(form.includes("upsertSellerProduct"));
assert(form.includes("CategoryTreeSelect"));
assert(form.includes("ProductTypeSelector"));
assert(form.includes("physicalGateActive"));
assert(form.includes("goToStep"));
assert(form.includes("startBusinessVerification"));
assert(form.includes("Submit for review") || form.includes("submit for review") || form.includes("Submitting"));
const selector = read("components/product/ProductTypeSelector.tsx");
assert(selector.includes("Physical products require business verification"));
assert(selector.includes("Verify business"));
assert(selector.includes('role="radiogroup"'));
assert(selector.indexOf("Digital") < selector.indexOf("Physical"));
const seller = read("lib/actions/seller-products.ts");
assert(seller.includes("Digital → Physical") || seller.includes("digital") && seller.includes("physical"));
assert(seller.includes("assertCanCreateProductType"));
const webhook = read("app/api/webhooks/didit/route.ts");
assert(webhook.includes("isBusinessSession"));
assert(webhook.includes('verification_status: "verified"'));
const tax = read("lib/products/digital-taxonomy.ts");
assert(tax.includes("Education & Learning"));
assert(tax.includes("AI & Automation"));
console.log("✅ Product upload gate + taxonomy verification passed");
