/**
 * buildMediaKitPdf — renders a professional, shareable one/two-pager for a
 * creator's Identity profile (headline, scores, social reach, earnings,
 * portfolio, testimonials/reviews, contact). Branded with Jimvio orange.
 * Mirrors the layout conventions in `lib/orders/invoice-pdf.ts`.
 */

import { createPdfDocument, type PdfDocumentInstance } from "@/lib/pdf/pdfkit-server";
import { PDF_FONT_BOLD, PDF_FONT_REGULAR, resetPdfCursor, sanitizePdfText } from "@/lib/pdf/export-fonts";
import type { IdentityCreatorStatsSnapshot, IdentityProfilePayload } from "@/lib/identity/types";

const MARGIN = 50;
const BRAND = "#FF5A1F";
const INK = "#111111";
const MUTED = "#6b7280";
const LIGHT_BG = "#fff4ec";
const FOOTER_ZONE = 40;

function s(value: string | null | undefined): string {
  return sanitizePdfText(value ?? "");
}

function contentBottom(doc: PdfDocumentInstance): number {
  return doc.page.height - doc.page.margins.bottom - FOOTER_ZONE;
}

function formatNumber(value: number): string {
  if (value >= 1_000_000) return `${(value / 1_000_000).toFixed(1)}M`;
  if (value >= 1_000) return `${(value / 1_000).toFixed(1)}K`;
  return String(Math.round(value));
}

function formatMoney(value: number): string {
  return `$${value.toLocaleString(undefined, { minimumFractionDigits: 0, maximumFractionDigits: 2 })}`;
}

function drawFooter(doc: PdfDocumentInstance, pageWidth: number, left: number, username: string | null) {
  const footerY = doc.page.height - doc.page.margins.bottom - 24;
  doc.font(PDF_FONT_REGULAR).fontSize(8).fillColor(MUTED);
  doc.text(
    s(`Generated by Jimvio${username ? ` — jimvio.com/u/${username}` : ""}`),
    left,
    footerY,
    { width: pageWidth, align: "left" }
  );
}

function ensureSpace(doc: PdfDocumentInstance, needed: number) {
  if (doc.y + needed > contentBottom(doc)) {
    doc.addPage({ size: "A4", margin: MARGIN });
    resetPdfCursor(doc);
  }
}

function drawStatChip(
  doc: PdfDocumentInstance,
  x: number,
  y: number,
  width: number,
  label: string,
  value: string
) {
  doc.roundedRect(x, y, width, 52, 6).fillAndStroke(LIGHT_BG, LIGHT_BG);
  doc.font(PDF_FONT_BOLD).fontSize(16).fillColor(INK).text(s(value), x + 12, y + 8, { width: width - 24 });
  doc.font(PDF_FONT_REGULAR).fontSize(8).fillColor(MUTED).text(s(label).toUpperCase(), x + 12, y + 32, {
    width: width - 24,
  });
}

export function buildMediaKitPdf(
  payload: IdentityProfilePayload,
  stats?: IdentityCreatorStatsSnapshot | null
): Promise<Buffer> {
  const effectiveStats = stats ?? payload.stats;

  return new Promise((resolve, reject) => {
    const doc = createPdfDocument({
      margin: MARGIN,
      size: "A4",
      bufferPages: true,
      autoFirstPage: true,
    });
    const chunks: Buffer[] = [];

    doc.on("data", (chunk) => chunks.push(chunk as Buffer));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
    const left = doc.page.margins.left;

    const { profile } = payload;

    // Brand bar
    doc.rect(0, 0, doc.page.width, 6).fill(BRAND);
    resetPdfCursor(doc);
    doc.moveDown(0.6);

    doc.font(PDF_FONT_BOLD).fontSize(12).fillColor(BRAND).text("JIMVIO MEDIA KIT");
    doc.moveDown(0.6);

    // Name + headline
    doc.font(PDF_FONT_BOLD).fontSize(24).fillColor(INK).text(s(profile.fullName || profile.username || "Creator"));
    if (profile.username) {
      doc.font(PDF_FONT_REGULAR).fontSize(11).fillColor(MUTED).text(s(`@${profile.username}`));
    }
    if (profile.headline) {
      doc.moveDown(0.3);
      doc.font(PDF_FONT_REGULAR).fontSize(12).fillColor(INK).text(s(profile.headline), { width: pageWidth });
    }

    doc.moveDown(0.4);
    const badges: string[] = [];
    if (profile.isVerified) badges.push("Verified");
    if (profile.identityVerified) badges.push("Identity Verified");
    badges.push(`${profile.creatorLevel.charAt(0).toUpperCase()}${profile.creatorLevel.slice(1)} Creator`);
    if (badges.length) {
      doc.font(PDF_FONT_REGULAR).fontSize(9).fillColor(BRAND).text(s(badges.join("   •   ")));
    }

    if (profile.bio) {
      doc.moveDown(0.6);
      doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(MUTED).text(s(profile.bio), { width: pageWidth });
    }

    doc.moveDown(1);

    // Score + reputation chips
    doc.font(PDF_FONT_BOLD).fontSize(11).fillColor(INK).text("PERFORMANCE");
    doc.moveDown(0.4);
    const chipY = doc.y;
    const chipW = (pageWidth - 3 * 10) / 4;
    drawStatChip(doc, left, chipY, chipW, "Trust score", `${Math.round(profile.trustScore)}`);
    drawStatChip(doc, left + chipW + 10, chipY, chipW, "AI score", `${Math.round(profile.aiScore)}`);
    drawStatChip(
      doc,
      left + (chipW + 10) * 2,
      chipY,
      chipW,
      "Rating",
      profile.reviewCount > 0 ? `${profile.avgRating.toFixed(1)} / 5` : "New"
    );
    drawStatChip(
      doc,
      left + (chipW + 10) * 3,
      chipY,
      chipW,
      "Response time",
      profile.responseTimeHours != null ? `${Math.round(profile.responseTimeHours)}h` : "—"
    );
    doc.y = chipY + 52;
    doc.moveDown(1);

    // Social reach
    if (payload.social.length) {
      ensureSpace(doc, 24 + payload.social.length * 18);
      doc.font(PDF_FONT_BOLD).fontSize(11).fillColor(INK).text("SOCIAL REACH");
      doc.moveDown(0.3);
      const totalFollowers = payload.social.reduce((sum, acc) => sum + acc.followers, 0);
      doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(MUTED).text(
        s(`${formatNumber(totalFollowers)} total followers across ${payload.social.length} platform${payload.social.length === 1 ? "" : "s"}`)
      );
      doc.moveDown(0.4);
      for (const account of payload.social) {
        ensureSpace(doc, 16);
        const platformLabel = account.platform.charAt(0).toUpperCase() + account.platform.slice(1);
        doc.font(PDF_FONT_BOLD).fontSize(10).fillColor(INK).text(s(platformLabel), left, doc.y, {
          width: pageWidth * 0.3,
          continued: false,
        });
        doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(MUTED).text(
          s(`${formatNumber(account.followers)} followers   •   ${account.engagementRate.toFixed(1)}% engagement${account.isVerified ? "   •   Verified" : ""}`),
          left + pageWidth * 0.3,
          doc.y - 12,
          { width: pageWidth * 0.7 }
        );
      }
      doc.moveDown(0.8);
    }

    // Earnings / cross-surface summary
    if (effectiveStats) {
      const lines: string[] = [];
      if (effectiveStats.ugc.campaignsCompleted > 0 || effectiveStats.ugc.earningsPaid > 0) {
        lines.push(
          `UGC: ${effectiveStats.ugc.campaignsCompleted} campaigns completed, ${formatMoney(effectiveStats.ugc.earningsPaid)} earned, ${effectiveStats.ugc.approvalRate}% approval rate`
        );
      }
      if (effectiveStats.affiliate.isAffiliate) {
        lines.push(
          `Affiliate: ${formatMoney(effectiveStats.affiliate.totalEarnings)} total earnings, ${effectiveStats.affiliate.conversionRate}% conversion rate`
        );
      }
      if (effectiveStats.marketplace.isVendor) {
        lines.push(
          `Marketplace: ${effectiveStats.marketplace.productsCount} products, ${formatMoney(effectiveStats.marketplace.totalRevenue)} revenue`
        );
      }
      if (lines.length) {
        ensureSpace(doc, 24 + lines.length * 16);
        doc.font(PDF_FONT_BOLD).fontSize(11).fillColor(INK).text("EARNINGS SUMMARY");
        doc.moveDown(0.3);
        for (const line of lines) {
          doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(MUTED).text(s(line), { width: pageWidth });
        }
        doc.moveDown(0.8);
      }
    }

    // Portfolio highlights
    const featuredPortfolio = payload.portfolio.filter((p) => p.isPublic).slice(0, 8);
    if (featuredPortfolio.length) {
      ensureSpace(doc, 24 + featuredPortfolio.length * 16);
      doc.font(PDF_FONT_BOLD).fontSize(11).fillColor(INK).text("PORTFOLIO");
      doc.moveDown(0.3);
      for (const item of featuredPortfolio) {
        ensureSpace(doc, 16);
        const brandSuffix = item.brandName ? ` — ${item.brandName}` : "";
        doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(INK).text(s(`•  ${item.title}${brandSuffix}`), {
          width: pageWidth,
        });
      }
      doc.moveDown(0.8);
    }

    // Testimonials / verified reviews
    const highlights = [
      ...payload.testimonials.map((t) => ({ quote: t.quote, author: t.authorName, role: t.authorRole })),
      ...payload.reviews
        .filter((r) => r.isVerified)
        .slice(0, 5)
        .map((r) => ({
          quote: r.body,
          author: r.reviewer?.fullName ?? r.reviewer?.username ?? "Verified partner",
          role: r.direction === "brand_to_creator" ? "Brand" : "Creator",
        })),
    ].slice(0, 6);

    if (highlights.length) {
      ensureSpace(doc, 40);
      doc.font(PDF_FONT_BOLD).fontSize(11).fillColor(INK).text("WHAT PARTNERS SAY");
      doc.moveDown(0.3);
      for (const h of highlights) {
        ensureSpace(doc, 36);
        doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(INK).text(s(`"${h.quote}"`), { width: pageWidth });
        doc.font(PDF_FONT_BOLD).fontSize(9).fillColor(MUTED).text(s(`— ${h.author}${h.role ? `, ${h.role}` : ""}`));
        doc.moveDown(0.4);
      }
      doc.moveDown(0.4);
    }

    // Contact
    ensureSpace(doc, 60);
    doc.font(PDF_FONT_BOLD).fontSize(11).fillColor(INK).text("CONTACT");
    doc.moveDown(0.3);
    const contactLines: string[] = [];
    if (profile.username) contactLines.push(`jimvio.com/u/${profile.username}`);
    if (profile.website) contactLines.push(profile.website);
    if (profile.city || profile.country) {
      contactLines.push([profile.city, profile.country].filter(Boolean).join(", "));
    }
    for (const line of contactLines) {
      doc.font(PDF_FONT_REGULAR).fontSize(10).fillColor(MUTED).text(s(line));
    }

    const range = doc.bufferedPageRange();
    if (range.count > 0) {
      for (let i = 0; i < range.count; i++) {
        doc.switchToPage(range.start + i);
        drawFooter(doc, pageWidth, left, profile.username);
      }
      doc.switchToPage(range.start + range.count - 1);
    }
    resetPdfCursor(doc);

    doc.end();
  });
}
