const DICTS: Record<UgcLocale, typeof EN> = { en: EN, fr: FR, rw: RW };

export type UgcMessageKey = keyof typeof EN;

export function ugcMessage(
  locale: UgcLocale,
  key: UgcMessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = DICTS[locale][key] ?? DICTS.en[key] ?? String(key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function ugcStatusLabel(locale: UgcLocale, status: string): string {
  const map: Record<string, UgcMessageKey> = {
    accepted: "statusAccepted",
    pending: "pending",
    waitlisted: "statusWaitlisted",
    withdrawn: "statusWithdrawn",
    revision_requested: "statusRevisionRequested",
    submitted: "statusSubmitted",
    approved: "approved",
    paid: "statusPaid",
    rejected: "rejected",
    completed: "statusCompleted",
    draft: "statusDraft",
    active: "statusActive",
    paused: "statusPaused",
    cancelled: "statusCancelled",
    funded: "funded",
  };
  const key = map[status];
  return key ? ugcMessage(locale, key) : status.replaceAll("_", " ");
}

