const DICTS: Record<UgcLocale, typeof EN> = { en: EN, fr: FR, rw: RW };

export type UgcMessageKey = keyof typeof EN;

export function ugcMessage(locale: UgcLocale, key: UgcMessageKey): string {
  return DICTS[locale][key] ?? DICTS.en[key];
}

